    @Test
    fun testRedshiftSpecificFunctionSql() {
        val table = object : Table("redshift_functions") {
            val name = varchar("name", 32)
            val flags = integer("flags")
        }

        withRedshiftDialect {
            assertEquals("RANDOM()", Random(seed = 42).toString())
            assertEquals(
                "'one' || '-' || 'two' || '-' || 'three'",
                concat("-", listOf(stringLiteral("one"), stringLiteral("two"), stringLiteral("three"))).toString()
            )
            assertEquals(
                "'one' || '''' || 'two'",
                concat("'", listOf(stringLiteral("one"), stringLiteral("two"))).toString()
            )

            val name = fullIdentity(table.name)
            assertEquals("$name ~ '^[A-Z]'", table.name.regexp(stringLiteral("^[A-Z]")).toString())
            assertFailsWith<UnsupportedByDialectException> {
                table.name.regexp(stringLiteral("^[a-z]"), caseSensitive = false).toString()
            }

            val flags = fullIdentity(table.flags)
            assertEquals("($flags+7-($flags & 7))", (table.flags bitwiseOr 7).toString())
            assertEquals("(($flags+7-($flags & 7))-($flags & 7))", (table.flags bitwiseXor 7).toString())
        }
    }

    @Test
    fun testExplainSupportsOnlyRedshiftSyntax() {
        withRedshiftDialect {
            val functionProvider = currentDialect.functionProvider
            assertEquals("EXPLAIN SELECT 1", functionProvider.explain(false, null, "SELECT 1", this))
            assertEquals("EXPLAIN VERBOSE SELECT 1", functionProvider.explain(false, "VERBOSE", "SELECT 1", this))
            assertFailsWith<UnsupportedByDialectException> {
                functionProvider.explain(true, null, "SELECT 1", this)
            }
            assertFailsWith<UnsupportedByDialectException> {
                functionProvider.explain(false, "FORMAT JSON", "SELECT 1", this)
            }
        }
    }

    @Test
    fun testUpsertUsesTypedRedshiftMergeSourceQuery() {
        val table = object : Table("redshift_upsert") {
            val code = varchar("code", 32)
            val value = integer("value")
            val payload = binary("payload", 128)

            override val primaryKey = PrimaryKey(code)
        }

        withRedshiftDialect {
            val statement = buildStatement {
                table.upsert(table.code) {
                    it[code] = "A"
                    it[value] = 1
                    it[payload] = byteArrayOf(1, 2, 3)
                }
            }
            val codeName = identity(table.code)
            val valueName = identity(table.value)
            val payloadName = identity(table.payload)
            val expected = buildString {
                append("MERGE INTO ${identity(table)} ")
                append(
                    "USING (SELECT CAST(? AS VARCHAR(32)) AS $codeName, " +
                        "CAST(? AS INT) AS $valueName, CAST(? AS VARBYTE(128)) AS $payloadName " +
                        "FROM pg_catalog.pg_class LIMIT 1) AS S "
                )
                append("ON (${fullIdentity(table.code)}=S.$codeName) ")
                append("WHEN MATCHED THEN UPDATE SET $valueName=S.$valueName, $payloadName=S.$payloadName ")
                append("WHEN NOT MATCHED THEN INSERT ($codeName, $valueName, $payloadName) ")
                append("VALUES (S.$codeName, S.$valueName, S.$payloadName)")
            }

            assertEquals(expected, statement.prepareSQL(this, prepared = true))
            assertFalse(statement.prepareSQL(this, prepared = true).contains("(VALUES"))
        }
    }

    @Test
    fun testUpsertOmitsIdentityColumnFromInsertClause() {
        val table = object : Table("redshift_upsert_identity") {
            val id = integer("id").autoIncrement()
            val code = varchar("code", 32)
            val value = integer("value")

            override val primaryKey = PrimaryKey(code)
        }

        withRedshiftDialect {
            val statement = buildStatement {
                table.upsert(table.code) {
                    it[id] = 99
                    it[code] = "A"
                    it[value] = 1
                }
            }
            val sql = statement.prepareSQL(this, prepared = true)
            val updateClause = sql.substringAfter("WHEN MATCHED THEN UPDATE SET ").substringBefore(" WHEN NOT MATCHED")
            val insertClause = sql.substringAfter("WHEN NOT MATCHED THEN INSERT ")

            assertContains(sql.substringBefore("WHEN NOT MATCHED"), "CAST(? AS INT) AS ${identity(table.id)}")
            assertFalse(updateClause.contains("${identity(table.id)}="))
            assertFalse(insertClause.substringBefore(" VALUES ").contains(identity(table.id)))
            assertEquals(
                "(${identity(table.code)}, ${identity(table.value)}) " +
                    "VALUES (S.${identity(table.code)}, S.${identity(table.value)})",
                insertClause
            )
        }
    }

    @Test
    fun testUnsupportedReturningAndDmlLimitsFailBeforeExecution() {
        val table = object : Table("redshift_dml") {
            val id = integer("id")
            val value = varchar("value", 32)

            override val primaryKey = PrimaryKey(id)
        }

        withRedshiftDialect {
            val returning = buildStatement {
                table.insertReturning {
                    it[id] = 1
                    it[value] = "A"
                }
            }
            assertFailsWith<UnsupportedByDialectException> {
                returning.prepareSQL(this, prepared = true)
            }

            val update = buildStatement {
                table.update(limit = 1) {
                    it[value] = "B"
                }
            }
            assertFailsWith<UnsupportedByDialectException> {
                update.prepareSQL(this, prepared = true)
            }

            val delete = buildStatement {
                table.deleteWhere(limit = 1) { id eq 1 }
            }
            assertFailsWith<UnsupportedByDialectException> {
                delete.prepareSQL(this, prepared = true)
            }
        }
    }

