    @Test
    fun testInsertDoesNotRequestGeneratedKeys() {
        val table = object : Table("redshift_generated_keys") {
            val id = integer("id").autoIncrement()
            val payload = varchar("payload", 32)
        }

        withRedshiftDialect {
            try {
                exec("CREATE TABLE redshift_generated_keys (id INTEGER NOT NULL, payload VARCHAR(32) NOT NULL)")
                val statement = buildStatement {
                    table.insert {
                        it[payload] = "A"
                    }
                }
                val prepared = InsertBlockingExecutable(statement).prepared(
                    this,
                    statement.prepareSQL(this, prepared = true)
                )

                try {
                    val jdbcPrepared = assertIs<JdbcPreparedStatementImpl>(prepared)
                    assertFalse(jdbcPrepared.wasGeneratedKeysRequested)
                } finally {
                    prepared.closeIfPossible()
                }
            } finally {
                exec("DROP TABLE IF EXISTS redshift_generated_keys")
            }
        }
    }

    @Test
    fun testReadingGeneratedIdReportsUnsupportedOperation() {
        val table = object : Table("redshift_generated_id") {
            val id = integer("id").autoIncrement()
            val payload = varchar("payload", 32)
        }

        withRedshiftDialect {
            try {
                exec(
                    "CREATE TABLE redshift_generated_id (" +
                        "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload VARCHAR(32) NOT NULL)"
                )
                val insert = table.insert {
                    it[payload] = "A"
                }

                val exception = assertFailsWith<UnsupportedByDialectException> {
                    insert[table.id]
                }
                assertContains(exception.message.orEmpty(), "redshift_generated_id.id")
            } finally {
                exec("DROP TABLE IF EXISTS redshift_generated_id")
            }
        }
    }

    private fun withRedshiftDialect(statement: JdbcTransaction.() -> Unit) {
        val database = Database.connect(
            url = "jdbc:h2:mem:redshift-${UUID.randomUUID()}",
            driver = TestDB.H2_V2.driver,
            databaseConfig = DatabaseConfig { explicitDialect = RedshiftDialect() }
        )
        try {
            transaction(database) {
                maxAttempts = 1
                statement()
            }
        } finally {
            TransactionManager.closeAndUnregister(database)
        }
    }
