    @Test
    fun testRedshiftDataTypesAndIdentityDdl() {
        val table = object : Table("redshift_types") {
            val id = long("id").autoIncrement()
            val externalId = uuid("external_id")
            val javaExternalId = javaUUID("java_external_id")
            val description = text("description")
            val payload = binary("payload", 128)
            val unboundedPayload = binary("unbounded_payload", Int.MAX_VALUE)
            val attachment = blob("attachment")
            val quantity = integer("quantity")

            override val primaryKey = PrimaryKey(id)
        }

        withRedshiftDialect {
            assertEquals("BIGINT GENERATED BY DEFAULT AS IDENTITY(1, 1)", table.id.columnType.sqlType())
            assertEquals("VARCHAR(36)", table.externalId.columnType.sqlType())
            assertEquals("VARCHAR(36)", table.javaExternalId.columnType.sqlType())
            assertEquals("VARCHAR(MAX)", table.description.columnType.sqlType())
            assertEquals("VARBYTE(128)", table.payload.columnType.sqlType())
            assertEquals("VARBYTE(16777216)", table.unboundedPayload.columnType.sqlType())
            assertEquals("VARBYTE(16777216)", table.attachment.columnType.sqlType())

            val createTable = table.ddl.single()
            assertContains(createTable, "GENERATED BY DEFAULT AS IDENTITY(1, 1)")
            assertFalse(createTable.contains("CHECK"))
            assertFalse(currentDialect.supportsGeneratedKeysRetrieval)
            assertFalse(currentDialect.supportsCreateSequence)
            val undashedUuid = "00112233445566778899aabbccddeeff"
            val dashedUuid = "00112233-4455-6677-8899-aabbccddeeff"
            assertEquals(kotlin.uuid.Uuid.parseHex(undashedUuid), table.externalId.columnType.valueFromDB(undashedUuid))
            assertEquals(UUID.fromString(dashedUuid), table.javaExternalId.columnType.valueFromDB(undashedUuid))
            assertFailsWith<IllegalStateException> {
                table.externalId.columnType.valueFromDB("not-a-uuid")
            }
            assertFailsWith<IllegalStateException> {
                table.javaExternalId.columnType.valueFromDB("not-a-uuid")
            }
        }
    }

    @Test
    fun testCheckConstraintWarningsUseEffectiveConstraintsAndNameTable() {
        val tableWithoutEffectiveChecks = object : Table("redshift_without_effective_checks") {
            val value = integer("value")
        }
        val tableWithRangeChecks = object : Table("redshift_with_range_checks") {
            val signedByte = byte("signed_byte")
            val unsignedByte = ubyte("unsigned_byte")
            val unsignedShort = ushort("unsigned_short")
        }
        val tableWithCheck = object : Table("redshift_with_check") {
            val value = integer("value").check("positive_value") { it greater 0 }
        }

        withRedshiftDialect {
            val logCaptor = LogCaptor.forName(exposedLogger.name)
            try {
                tableWithoutEffectiveChecks.ddl
                assertTrue(logCaptor.warnLogs.isEmpty())

                assertFalse(tableWithRangeChecks.ddl.single().contains(" CHECK "))
                assertContains(logCaptor.warnLogs.single(), identity(tableWithRangeChecks))
                logCaptor.clearLogs()

                tableWithCheck.ddl
                val warning = logCaptor.warnLogs.single()
                assertContains(warning, identity(tableWithCheck))
                assertContains(warning, RedshiftDialect.dialectName)
            } finally {
                logCaptor.clearLogs()
                logCaptor.close()
            }
        }
    }

    @Test
    fun testForeignKeyActionsAndChecksAreOmitted() {
        val parent = object : Table("redshift_parent") {
            val id = integer("id")
            override val primaryKey = PrimaryKey(id)
        }
        val child = object : Table("redshift_child") {
            val parentId = integer("parent_id").references(
                parent.id,
                onDelete = ReferenceOption.CASCADE,
                onUpdate = ReferenceOption.CASCADE
            )
        }

        withRedshiftDialect {
            val createTable = child.ddl.single()
            assertContains(createTable, "FOREIGN KEY")
            assertFalse(createTable.contains("ON DELETE"))
            assertFalse(createTable.contains("ON UPDATE"))
            assertFalse(createTable.contains("CHECK"))
        }
    }

    @Test
    fun testUnsupportedIndexesAreSkippedAndUniqueConstraintsAreCreated() {
        val table = object : Table("redshift_indices") {
            val code = varchar("code", 32).index()
        }

        withRedshiftDialect {
            val logCaptor = LogCaptor.forName(exposedLogger.name)
            try {
                val createStatements = SchemaUtils.createStatements(table)
                assertTrue(createStatements.all { it.isNotBlank() })
                assertEquals(1, createStatements.size)
                logCaptor.clearLogs()

                SchemaUtils.create(table, inBatch = true)
                assertTrue(table.exists())

                val warning = logCaptor.warnLogs.single()
                assertContains(warning, table.tableName)
                assertContains(warning, "will not be created")
                assertTrue(table.indices.single().createStatement().isEmpty())
                assertTrue(table.indices.single().dropStatement().isEmpty())

                val uniqueConstraint = Index(
                    columns = listOf(table.code),
                    unique = true,
                    customName = "uq_redshift_indices_code"
                ).createStatement().single()
                assertContains(uniqueConstraint, "ADD CONSTRAINT")
                assertContains(uniqueConstraint, "UNIQUE")
            } finally {
                SchemaUtils.drop(table)
                logCaptor.clearLogs()
                logCaptor.close()
            }
        }
    }

