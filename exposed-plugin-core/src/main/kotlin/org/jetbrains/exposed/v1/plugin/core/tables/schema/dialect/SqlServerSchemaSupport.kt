package org.jetbrains.exposed.v1.plugin.core.tables.schema.dialect

import java.sql.Connection
import java.sql.PreparedStatement
import java.sql.ResultSet

/**
 * Responsible for obtaining non-standard metadata from a SQL Server database.
 *
 * The driver reports tables, keys, indices and foreign keys reliably, but its column metadata is not enough: it leaves
 * out `JSON` and `VECTOR` columns altogether, reports a `rowversion` column as `timestamp`, and says nothing about the
 * expression of a computed column, the seed of an identity column, the condition of a filtered index or the kind of a
 * temporal table. All of these are read from the `sys` catalog views instead.
 */
internal object SqlServerSchemaSupport : DialectSchemaSupport {
    override val syntax: DialectSyntax = SqlServerSyntax

    override val createsIndexForForeignKeys: Boolean = false

    override val supportsSchemas: Boolean = true

    override val schemasAreCatalogs: Boolean = false

    // Every database comes with `sys`, `INFORMATION_SCHEMA`, `guest` and one schema per fixed database role (`db_owner`,
    // `db_datareader` and so on), none of which hold user tables
    override fun isSystemSchema(connection: Connection, name: String): Boolean {
        val lowerCaseName = name.lowercase()
        return lowerCaseName in SYSTEM_SCHEMAS || lowerCaseName.startsWith(ROLE_SCHEMA_PREFIX)
    }

    // Includes the columns that the driver does not list, so that they can be reported, see [SqlServerSyntax.unmappedTypes]
    override fun declaredColumnTypes(
        connection: Connection,
        schema: String,
        tableName: String
    ): Map<String, String> {
        return columns(connection, schema, tableName).associate { it.name to it.normalizedType() }
    }

    // A computed column has its expression in the catalog, wrapped in parentheses. The period columns of a temporal
    // table are filled in by the database as well, and are not reported as generated by the driver
    override fun generatedColumns(connection: Connection, schema: String, tableName: String): Map<String, String> {
        return columns(connection, schema, tableName).mapNotNull { column ->
            val expression = when {
                column.computedDefinition != null -> column.computedDefinition.withoutWrappingParentheses()
                column.generatedAlwaysType == GENERATED_AS_ROW_START -> "ROW START"
                column.generatedAlwaysType == GENERATED_AS_ROW_END -> "ROW END"
                else -> return@mapNotNull null
            }
            column.name to expression
        }.toMap()
    }

    // A `UNIQUE` constraint and the index that backs it share one name
    override fun uniqueConstraintNames(connection: Connection, schema: String, tableName: String): Map<String, String> {
        return connection.query(
            "SELECT name FROM sys.key_constraints WHERE parent_object_id = OBJECT_ID(QUOTENAME(?) + '.' + QUOTENAME(?)) AND type = 'UQ'",
            schema,
            tableName,
        ) { rs ->
            buildMap {
                while (rs.next()) {
                    put(rs.getString("name"), rs.getString("name"))
                }
            }
        }
    }

    override fun sequenceParameters(
        connection: Connection,
        schema: String,
        sequenceName: String,
        sequenceMaxValue: Long
    ): SequenceParameters? {
        return connection.query(
            "SELECT CAST(start_value AS BIGINT) AS start_value, CAST(increment AS BIGINT) AS increment, " +
                "CAST(minimum_value AS BIGINT) AS minimum_value, CAST(maximum_value AS BIGINT) AS maximum_value, is_cycling, cache_size " +
                "FROM sys.sequences WHERE SCHEMA_NAME(schema_id) = ? AND name = ?",
            schema,
            sequenceName,
        ) { rs ->
            if (!rs.next()) return@query null
            // the cache size is null unless one was declared, which leaves it to the database
            val cache = rs.getLong("cache_size").takeUnless { rs.wasNull() }
            SequenceParameters(
                startWith = rs.getLong("start_value").takeIf { it != IMPLIED_SEQUENCE_START },
                incrementBy = rs.getLong("increment").takeIf { it != DEFAULT_SEQUENCE_INCREMENT },
                minValue = rs.getLong("minimum_value").takeIf { it != IMPLIED_SEQUENCE_MINIMUM },
                maxValue = rs.getLong("maximum_value").takeIf { it != sequenceMaxValue },
                cycle = true.takeIf { rs.getBoolean("is_cycling") },
                cache = cache,
            ).takeUnless { it.isDefault }
        }
    }

    // An identity column never owns a separate sequence object
    override fun ownedSequences(connection: Connection, schema: String, tableName: String): Map<String, String> = emptyMap()

    // Exposed lists the sequences of every schema of the database, under their bare names
    override fun sequences(connection: Connection, schemas: List<String>): List<SequenceReference> {
        return schemas.flatMap { schema ->
            connection.query("SELECT name FROM sys.sequences WHERE SCHEMA_NAME(schema_id) = ? ORDER BY name", schema) { rs ->
                buildList {
                    while (rs.next()) {
                        add(SequenceReference(schema, rs.getString("name")))
                    }
                }
            }
        }
    }

    override fun enumerationTypes(connection: Connection, schema: String): Map<String, List<String>> = emptyMap()

    // The driver reports every foreign key, with its target schema and its rules
    override fun foreignKeys(
        connection: Connection,
        schema: String,
        tableName: String
    ): List<ReportedForeignKeyColumn>? = null

    // An identity column is generated as `autoIncrement()`, which declares `IDENTITY(1,1)`
    override fun columnOverrides(connection: Connection, schema: String, tableName: String): Map<String, ColumnOverride> {
        return columns(connection, schema, tableName)
            .filter { it.identitySeed != null && (it.identitySeed != DEFAULT_IDENTITY_VALUE || it.identityIncrement != DEFAULT_IDENTITY_VALUE) }
            .associate { column ->
                column.name to ColumnOverride(
                    unsupportedNote = "Column '${column.name}' of table '$tableName' is declared with " +
                        "IDENTITY(${column.identitySeed},${column.identityIncrement}), a seed and an increment that the generated " +
                        "autoIncrement() does not declare. A table created from this definition starts at 1 and increments by 1"
                )
            }
    }

    // A default is stored wrapped in parentheses, twice for a number: `((42))`, `('text')`, `(getdate())`, `(NULL)`.
    // The wrapping is removed, so that a default arrives in the form that the driver of other databases reports
    override fun columnDefaults(connection: Connection, schema: String, tableName: String): Map<String, String?> {
        return columns(connection, schema, tableName).associate { column ->
            column.name to column.defaultDefinition
                ?.let { normalizeDefault(it, isDateColumn = column.typeName.equals("date", ignoreCase = true)) }
        }
    }

    override fun indexFilters(connection: Connection, schema: String, tableName: String): Map<String, String> {
        return connection.query(
            "SELECT name, filter_definition FROM sys.indexes " +
                "WHERE object_id = OBJECT_ID(QUOTENAME(?) + '.' + QUOTENAME(?)) AND has_filter = 1 AND name IS NOT NULL",
            schema,
            tableName,
        ) { rs ->
            buildMap {
                while (rs.next()) {
                    put(rs.getString("name"), rs.getString("filter_definition").orEmpty().withoutWrappingParentheses())
                }
            }
        }
    }

    override fun indexExpressions(
        connection: Connection,
        schema: String,
        tableName: String
    ): Map<String, List<String>> = emptyMap()

    // A temporal table and its history table are both listed as ordinary tables by the driver
    override fun unsupportedTableNote(connection: Connection, schema: String, tableName: String): String? {
        val (temporalType, currentTable) = connection.query(
            "SELECT t.temporal_type, (SELECT TOP 1 p.name FROM sys.tables p WHERE p.history_table_id = t.object_id) AS current_table " +
                "FROM sys.tables t WHERE t.object_id = OBJECT_ID(QUOTENAME(?) + '.' + QUOTENAME(?))",
            schema,
            tableName,
        ) { rs -> if (rs.next()) rs.getInt("temporal_type") to rs.getString("current_table") else return null }
        return when (temporalType) {
            SYSTEM_VERSIONED_TEMPORAL_TABLE ->
                "Table '$tableName' is a system-versioned temporal table (SYSTEM_VERSIONING = ON), which the generated definition does " +
                    "not declare. Statements made through the definition see and change current rows only, and row history cannot be " +
                    "queried through it. A table created from this definition is not versioned, and no table option can add that, " +
                    "since the period columns must be declared as such with the table"
            HISTORY_TABLE ->
                "Table '$tableName' is the history table of the system-versioned temporal table '$currentTable'. Its rows are written " +
                    "by the database, so the generated definition can be used to query row history, but not to insert, update or delete"
            else -> null
        }
    }

    /** A column of a table as the `sys` catalog views report it. */
    private data class Column(
        val name: String,
        /** The name of the column's type, which for a `VECTOR` or an alias type differs from the type that stores it. */
        val typeName: String,
        /** The storage size in bytes, or -1 for a `MAX` type. */
        val maxLength: Int,
        val precision: Int,
        val scale: Int,
        val computedDefinition: String?,
        val generatedAlwaysType: Int,
        val defaultDefinition: String?,
        val identitySeed: String?,
        val identityIncrement: String?,
    ) {
        /** The type in the mapper's vocabulary when it has an exact Exposed function, and under its own name otherwise. */
        @Suppress("CyclomaticComplexMethod")
        fun normalizedType(): String = when (val type = typeName.lowercase()) {
            // the only unsigned integer type, which holds 0 to 255
            "tinyint" -> "TINYINT UNSIGNED"
            "smallint", "int", "bigint" -> type.uppercase()
            "bit" -> "BOOLEAN"
            "decimal", "numeric" -> "DECIMAL($precision, $scale)"
            // FLOAT(25) to FLOAT(53) and DOUBLE PRECISION are all stored as an 8-byte `float`; FLOAT(1) to FLOAT(24) as `real`
            "float" -> "DOUBLE PRECISION"
            "char" -> "CHAR($maxLength)"
            "varchar" -> if (maxLength == MAX_LENGTH) "CLOB" else "VARCHAR($maxLength)"
            "nchar" -> "NCHAR(${maxLength / BYTES_PER_NATIONAL_CHARACTER})"
            "nvarchar" -> if (maxLength == MAX_LENGTH) "NCLOB" else "NVARCHAR(${maxLength / BYTES_PER_NATIONAL_CHARACTER})"
            "binary" -> "BINARY($maxLength)"
            "varbinary" -> if (maxLength == MAX_LENGTH) "BLOB" else "VARBINARY($maxLength)"
            "uniqueidentifier" -> "UUID"
            "date" -> "DATE"
            // Exposed declares these three without a precision, which is the default of 7 fractional digits. Any other
            // precision keeps a name that the mapper has no function for
            "time" -> if (scale == DEFAULT_FRACTIONAL_SECONDS_PRECISION) "TIME" else "TIME($scale)"
            "datetime2" -> if (scale == DEFAULT_FRACTIONAL_SECONDS_PRECISION) "TIMESTAMP" else "DATETIME2($scale)"
            "datetimeoffset" -> if (scale == DEFAULT_FRACTIONAL_SECONDS_PRECISION) "TIMESTAMP WITH TIME ZONE" else "DATETIMEOFFSET($scale)"
            // not a date-time at all, but a counter that the database advances with every change of the row
            "timestamp" -> "ROWVERSION"
            // stored as a header followed by 4 bytes for each dimension
            "vector" -> "VECTOR(${(maxLength - VECTOR_HEADER_BYTES) / BYTES_PER_VECTOR_DIMENSION})"
            else -> type.uppercase()
        }
    }

    private fun columns(connection: Connection, schema: String, tableName: String): List<Column> {
        return connection.query(
            "SELECT c.name, TYPE_NAME(c.user_type_id) AS type_name, c.max_length, c.precision, c.scale, c.generated_always_type, " +
                "cc.definition AS computed_definition, d.definition AS default_definition, " +
                "CAST(ic.seed_value AS VARCHAR(40)) AS identity_seed, CAST(ic.increment_value AS VARCHAR(40)) AS identity_increment " +
                "FROM sys.columns c " +
                "LEFT JOIN sys.computed_columns cc ON cc.object_id = c.object_id AND cc.column_id = c.column_id " +
                "LEFT JOIN sys.default_constraints d ON d.parent_object_id = c.object_id AND d.parent_column_id = c.column_id " +
                "LEFT JOIN sys.identity_columns ic ON ic.object_id = c.object_id AND ic.column_id = c.column_id " +
                "WHERE c.object_id = OBJECT_ID(QUOTENAME(?) + '.' + QUOTENAME(?)) ORDER BY c.column_id",
            schema,
            tableName,
        ) { rs ->
            buildList {
                while (rs.next()) {
                    add(
                        Column(
                            name = rs.getString("name"),
                            typeName = rs.getString("type_name").orEmpty(),
                            maxLength = rs.getInt("max_length"),
                            precision = rs.getInt("precision"),
                            scale = rs.getInt("scale"),
                            computedDefinition = rs.getString("computed_definition"),
                            generatedAlwaysType = rs.getInt("generated_always_type"),
                            defaultDefinition = rs.getString("default_definition"),
                            identitySeed = rs.getString("identity_seed"),
                            identityIncrement = rs.getString("identity_increment"),
                        )
                    )
                }
            }
        }
    }

    /**
     * Brings a default, as the catalog stores it, to the form that the driver of other databases reports: without the
     * wrapping parentheses, with a string in plain single quotes, and with `getdate()` under the standard name of what
     * Exposed declares it for. `DEFAULT NULL` is no default at all.
     */
    internal fun normalizeDefault(definition: String, isDateColumn: Boolean): String? {
        val value = definition.withoutWrappingParentheses()
        return when {
            value.equals("NULL", ignoreCase = true) -> null
            // a string that was declared as Unicode
            NATIONAL_STRING_PATTERN.matches(value) -> value.substring(1)
            // a whole number outside the range of INT is stored as a decimal without digits after the point
            WHOLE_DECIMAL_PATTERN.matches(value) -> value.dropLast(1)
            // what the database stores for CURRENT_TIMESTAMP as well, and what Exposed writes for CurrentDate on a DATE column
            value.equals("getdate()", ignoreCase = true) -> if (isDateColumn) "CURRENT_DATE" else "CURRENT_TIMESTAMP"
            else -> value
        }
    }

    /** Removes every pair of parentheses that wraps the whole of this expression, as in `((42))` or `(getdate())`. */
    private fun String.withoutWrappingParentheses(): String {
        var expression = trim()
        while (expression.length >= 2 && expression.first() == '(' && expression.closingParenthesisOfFirst() == expression.lastIndex) {
            expression = expression.substring(1, expression.lastIndex).trim()
        }
        return expression
    }

    /** The index of the parenthesis that closes the one this expression starts with, ignoring any inside a string. */
    private fun String.closingParenthesisOfFirst(): Int {
        var depth = 0
        var inString = false
        forEachIndexed { index, char ->
            when {
                char == '\'' -> inString = !inString
                inString -> Unit
                char == '(' -> depth++
                char == ')' -> if (--depth == 0) return index
            }
        }
        return -1
    }

    private val SYSTEM_SCHEMAS: Set<String> = setOf("sys", "information_schema", "guest")
    private const val ROLE_SCHEMA_PREFIX: String = "db_"

    private const val MAX_LENGTH: Int = -1
    private const val BYTES_PER_NATIONAL_CHARACTER: Int = 2
    private const val VECTOR_HEADER_BYTES: Int = 8
    private const val BYTES_PER_VECTOR_DIMENSION: Int = 4
    private const val DEFAULT_FRACTIONAL_SECONDS_PRECISION: Int = 7

    private const val GENERATED_AS_ROW_START: Int = 1
    private const val GENERATED_AS_ROW_END: Int = 2
    private const val HISTORY_TABLE: Int = 1
    private const val SYSTEM_VERSIONED_TEMPORAL_TABLE: Int = 2

    private const val DEFAULT_IDENTITY_VALUE: String = "1"

    /** What `autoIncrement("sequence")` declares when it creates a sequence. */
    private const val IMPLIED_SEQUENCE_START: Long = 1
    private const val IMPLIED_SEQUENCE_MINIMUM: Long = 1
    private const val DEFAULT_SEQUENCE_INCREMENT: Long = 1

    private val NATIONAL_STRING_PATTERN: Regex = Regex("""^N'(?:[^']|'')*'$""", RegexOption.DOT_MATCHES_ALL)
    private val WHOLE_DECIMAL_PATTERN: Regex = Regex("""^-?\d+\.$""")

    private inline fun <T> Connection.query(sql: String, vararg parameters: String, read: (ResultSet) -> T): T =
        prepareStatement(sql).use { statement: PreparedStatement ->
            parameters.forEachIndexed { index, parameter -> statement.setString(index + 1, parameter) }
            statement.executeQuery().use(read)
        }
}
