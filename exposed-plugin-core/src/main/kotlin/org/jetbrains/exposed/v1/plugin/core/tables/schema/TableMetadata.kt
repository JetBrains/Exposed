package org.jetbrains.exposed.v1.plugin.core.tables.schema

import org.jetbrains.exposed.v1.core.ReferenceOption
import org.jetbrains.exposed.v1.core.vendors.ColumnMetadata
import org.jetbrains.exposed.v1.plugin.core.tables.ColumnMapping
import org.jetbrains.exposed.v1.plugin.core.tables.schema.dialect.SequenceParameters

/**
 * Stores all table metadata retrieved by [SchemaReader], including identifier and column information.
 */
internal data class TableMetadata(
    /** The table identifier metadata. */
    val reference: TableReference,

    /** All columns of the table in ordinal position order. */
    val columns: List<ColumnInfo>,

    /** The primary key of the table, if one is defined. */
    val primaryKey: PrimaryKeyInfo?,

    /**
     * Indices spanning more than one column, sorted by name and excluding the index that backs the primary key.
     * Single-column indices are held by the [ColumnInfo] they belong to.
     */
    val compositeIndices: List<IndexMetadata>,

    /**
     * Foreign keys spanning more than one column, sorted by name. Single-column keys are held by the [ColumnInfo]
     * they belong to.
     */
    val compositeForeignKeys: List<ForeignKeyInfo> = emptyList(),
) {
    /**
     * Name of the table by Exposed's patterns.
     * @see TableReference.name
     */
    val name: String
        get() = reference.name
}

/**
 * Stores only table identifier metadata retrieved by [SchemaReader].
 * No column metadata is stored, so that the output can be planned before any columns are fetched.
 */
internal data class TableReference(
    /** Name of the schema holding the table, as reported by the database. */
    val schema: String,

    /** Name of the table, as reported by the database. */
    val tableName: String,

    /**
     * Name of the table's schema, quoted where necessary. This may be `null` when the table is in
     * the connection's current schema and needs no prefix.
     */
    val schemaName: String?,

    /** Name of the table without any schema prefix, quoted where necessary by Exposed's patterns. */
    val simpleName: String,
) {
    /**
     * Name of the table by Exposed's patterns and prefixed with [schemaName] when set.
     * This should be used specifically for `Table` constructors.
     */
    val name: String
        get() = schemaName?.let { "$it.$simpleName" } ?: simpleName
}

/**
 * Stores all metadata retrieved by [SchemaReader] for a single existing table column.
 */
internal data class ColumnInfo(
    /** The column metadata retrieved from JDBC metadata, with its name converted to match Exposed's patterns. */
    val metadata: ColumnMetadata,

    /**
     * The name of a sequence that supplies the column's default value, with the current schema prefix removed,
     * or `null` when the column has no such default.
     */
    val sequenceName: String? = null,

    /**
     * The parameters of a sequence that supplies the column's default value, or `null` when there is either
     * no sequence or parameters are not needed to get the next value.
     */
    val sequenceParameters: SequenceParameters? = null,

    /**
     * The expression that computes the column's value when it is always generated by the database,
     * or `null` for a regular column.
     */
    val generationExpression: String? = null,

    /** Metadata for any indices associated with this column alone, sorted by name. */
    val indices: List<IndexMetadata> = emptyList(),

    /** Any user-defined code configured for this column in place of the generated mapping. */
    val mapping: ColumnMapping? = null,

    /**
     * The enumeration type of the column when the database declares enumerations as named types (like PostgreSQL), or
     * `null` for any other column. Any database that shares possible values in the column type (like H2) leave this
     * `null` and the mapper parses them from the type instead.
     */
    val enumeration: EnumerationType? = null,

    /**
     * The column's default as reported by the database, including quotes, or `null` when the column has no default.
     * Unlike `ColumnMetadata.defaultDbValue`, which is sanitized for migration comparisons, this keeps a string
     * literal apart from an identifier or a function.
     */
    val reportedDefault: String? = null,

    /** Metadata for any foreign key associated with this column alone. */
    val foreignKey: ForeignKeyInfo? = null,
) {
    /**
     * Name of the column by Exposed's patterns.
     * @see ColumnMetadata.name
     */
    val name: String
        get() = metadata.name
}

/**
 * A named enumeration type that a column is declared with, for use with `customEnumeration(name, sql, ...)`.
 */
internal data class EnumerationType(
    /** The type exactly as the generated `sql` argument must use it, so that generated DDL names the existing type. */
    val sql: String,

    /** The values in declaration order. */
    val values: List<String>,
)

/**
 * Stores all metadata retrieved by [SchemaReader] for a single existing foreign key constraint.
 */
internal data class ForeignKeyInfo(
    /**
     * The name of the constraint by Exposed's patterns, or `null` when it has no name worth preserving.
     * The latter includes: a database-generated name or the default name that is assigned by Exposed.
     * Migration utility methods will never compare these key names.
     */
    val customName: String?,

    /** Names of the referencing columns in key order, quoted where necessary like [TableMetadata.name]. */
    val columnNames: List<String>,

    /** Schema of the referenced table, as reported by the database. */
    val targetSchema: String,

    /** Name of the referenced table, as reported by the database. */
    val targetTable: String,

    /** Names of the referenced columns in key order, quoted where necessary like [TableMetadata.name]. */
    val targetColumnNames: List<String>,

    /** The delete rule, or `null` when it is the dialect default assumed for an undeclared rule. */
    val onDelete: ReferenceOption? = null,

    /** The update rule, or `null` when it is the dialect default assumed for an undeclared rule. */
    val onUpdate: ReferenceOption? = null,
)

/**
 * Stores all metadata retrieved by [SchemaReader] for an existing tables' primary key.
 */
internal data class PrimaryKeyInfo(
    /** Names of the key columns in key order, quoted where necessary like [TableMetadata.name]. */
    val columnNames: List<String>,

    /**
     * The name of the primary key by Exposed's patterns, or `null` when it has no name worth preserving.
     * The latter includes: a database-generated name or the default name that is assigned by Exposed.
     */
    val customName: String? = null,
)

/**
 * Stores all metadata retrieved by [SchemaReader] for a single existing index on a table.
 */
internal data class IndexMetadata(
    /**
     * Name of the index, or of the `UNIQUE` constraint it backs on a database that names the two differently,
     * quoted where necessary like [TableMetadata.name].
     */
    val name: String,

    /** Names of the indexed columns in ordinal position order, quoted where necessary like [TableMetadata.name]. */
    val columnNames: List<String>,

    /** Whether the index enforces uniqueness. */
    val unique: Boolean,

    /**
     * Whether a generated definition can omit [name] and let Exposed assign its own default: either because [name] is
     * exactly that provided default, or because the database generated it for an unnamed `UNIQUE` constraint.
     */
    val isDefaultName: Boolean = false,
)
